import { describe, expect, it } from 'vitest';
import { enumerate, evaluate, inputsOf, type Configuration, type Outcome } from '../../src/core/chamber/enumerate';
import { parseChamber } from '../../src/core/chamber/parser';
import type { ChamberId } from '../../src/core/chamber/types';
import { CHAMBERS } from '../../src/data/chambers';

/**
 * The intended end state of each chamber, as logical inputs (decision log solutions). Plates list
 * what is weighed down at the end (crates, walkers); mirrors only the ones the player turns.
 */
const INTENDED: Record<ChamberId, Configuration & { note: string }> = {
  'W-E': { phase: 'red', mirrors: {}, plates: ['p', 'q'], note: 'crate on p (door), crate on q (exit)' },
  'W-M': { phase: 'red', mirrors: {}, plates: ['t', 'x'], note: 'walker on t (door K), crate on x (exit); s released' },
  'W-H': { phase: 'blue', mirrors: {}, plates: ['x', 'y'], note: 'crate dropped on x, walker dropped on y, Blue' },
  'L-E': { phase: 'red', mirrors: { mirrorA: '/', mirrorB: '\\' }, plates: [], note: 'both mirrors turned' },
  'L-M': { phase: 'red', mirrors: { M1: '\\', M2: '\\', M3: '\\' }, plates: [], note: 'all three mirrors turned' },
  'L-H': { phase: 'red', mirrors: { Mh: '\\', Mc: '\\' }, plates: ['a', 'b'], note: 'crate on a, walker on b, high mirror Bolted (corner mirror untouched)' },
  'P-E': { phase: 'blue', mirrors: {}, plates: [], note: 'exit is a doorway (always open)' },
  'P-M': { phase: 'red', mirrors: {}, plates: [], note: 'exit is a doorway (always open)' },
  'P-H': { phase: 'blue', mirrors: { mirror: '\\' }, plates: ['p', 'q'], note: 'crate on p, walker on qqq, mirror Bolted, Blue' },
  'G-E': { phase: 'red', mirrors: {}, plates: ['a'], note: 'crate fetched through gate 1 onto a' },
  'G-M': { phase: 'red', mirrors: {}, plates: ['a', 'x'], note: 'walker delivered by gate 2 onto a (gate 1 on), crate on x; c released' },
  'G-H': { phase: 'red', mirrors: { Ma: '\\' }, plates: ['p'], note: 'crate on p holds gate 2, Ma sends the beam through gate 1 to r2' },
};

const fmt = (o: Outcome) => {
  const mirrors = Object.entries(o.mirrors).map(([k, v]) => `${k}${v}`).join(' ');
  return `phase=${o.phase} · mirrors=[${mirrors}] · plates=[${o.plates.join(',')}] · lit=[${o.lit.join(',')}]`;
};

const same = (a: Configuration, b: Outcome) =>
  a.phase === b.phase && a.plates.slice().sort().join() === b.plates.slice().sort().join() &&
  Object.entries(b.mirrors).every(([k, v]) => (a.mirrors[k] ?? v) === v) && Object.entries(a.mirrors).every(([k, v]) => b.mirrors[k] === v);

describe('logic-state enumerator (C51)', () => {
  const lines: string[] = [
    '# Logic-state enumerator report',
    '',
    'Generated by `tests/core/enumerate.test.ts` (a file snapshot: the test fails if the chambers\' logic changes; review the diff, then update with `npx vitest run -u tests/core/enumerate.test.ts`).',
    '',
    'For every chamber it tries every combination of phase colour, free-mirror states and plates pressed, and lists the combinations that open the exit. ✓ marks the intended end state. Plates only say *something* is weighing them down; whether that is physically possible is the reachability checker\'s and the playtests\' job.',
    '',
  ];

  for (const def of Object.values(CHAMBERS)) {
    it(`${def.id}: the intended configuration opens the exit`, () => {
      const { model } = parseChamber(def);
      expect(evaluate(model!, INTENDED[def.id as ChamberId]).exitOpen).toBe(true);
    });
  }

  it('report (reviewed by hand)', async () => {
    for (const def of Object.values(CHAMBERS)) {
      const { model } = parseChamber(def);
      const inputs = inputsOf(model!);
      const all = enumerate(model!);
      const opening = all.filter((o) => o.exitOpen);
      lines.push(`## ${def.id} "${def.name}"`);
      lines.push(`- Inputs: phase ${inputs.phases.join('/')} · free mirrors [${inputs.mirrors.join(', ')}] · plates [${inputs.plates.join(', ')}] → ${all.length} configurations`);
      const intended = INTENDED[def.id as ChamberId];
      lines.push(`- Intended: ${intended.note}`);
      lines.push(`- The exit opens in ${opening.length} of ${all.length}:`);
      for (const o of opening) lines.push(`  - ${same(intended, o) ? '✓ ' : ''}${fmt(o)}`);
      lines.push('');
    }
    await expect(lines.join('\n')).toMatchFileSnapshot('../../docs/enumerator-report.md');
  });
});
